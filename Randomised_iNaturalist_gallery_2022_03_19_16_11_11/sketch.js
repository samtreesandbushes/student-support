// Select total number of images
totalNumberOfImages = 10;

// Set width and height of canvas
w = 1920;
h = 1080;

// Initiate some x and y values
y = [200,350,500,200,350,500,200,350,500];
x = [300,300,300,500,500,500,700,700,700];

j = 4;

r0 = 0;
r1 = 1;


// Create array to store images
let test = [];
let temp = [];

