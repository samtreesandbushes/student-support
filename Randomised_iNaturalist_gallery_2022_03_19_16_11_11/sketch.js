// THE MOUSE INTERACTION

function mouseClicked() {
  
  // randomise number of images shown
  j = random(4,10);
  
  // reset some randomised variables
  r0 = random(0, mouseX);
  r1 = random(0, 20);
  
  
  // shuffle contents of image array
  shuffle(test, true);
  

  /////////////////////////
  // Toggle fullscreen by clicking top left of display
  if (mouseX > 0 && mouseX < 100 && mouseY > 0 && mouseY < 100) {
    let fs = fullscreen();
    fullscreen(!fs);
  }
}
